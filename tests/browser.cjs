// Optional integration tests; not a dependency for using the website.
const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const {spawn}=require('node:child_process')
const path=require('node:path')
async function main(){
 const entry=process.env.CHECKIN_ENTRY||'index.html'
 const server=spawn('python3',['-m','http.server','8766','--bind','127.0.0.1'],{cwd:process.env.SITE_DIR||path.resolve(__dirname,'..'),stdio:'ignore'})
 let browser
 try{
  for(let i=0;i<50;i++){try{if((await fetch('http://127.0.0.1:8766')).ok)break}catch{}await new Promise(r=>setTimeout(r,100))}
  browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox']})
  const context=await browser.newContext({viewport:{width:1440,height:1100},acceptDownloads:true})
  const page=await context.newPage(),errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto('http://127.0.0.1:8766/'+entry)
  assert.equal(await page.title(),'青禾云课 · 学员端')
  assert.equal(await page.locator('#admin-panel').count(),0)
  assert.equal(await page.locator('.system-name').textContent(),'青禾云课')
  assert.ok(!(await page.locator('body').innerText()).includes('文化宫'))
  assert.equal(await page.locator('#course-sign').isDisabled(),true)
  assert.equal(await page.locator('#total').textContent(),'0')
  await page.locator('input[value=calligraphy]').check()
  await page.locator('#course-sign').click()
  assert.equal(await page.locator('#course-sign').isDisabled(),true)
  assert.equal(await page.locator('#total').textContent(),'1')
  await page.locator('input[value=dance]').check()
  await page.locator('#course-sign').click()
  assert.equal(await page.locator('#total').textContent(),'2')
  await page.reload()
  assert.equal(await page.locator('#total').textContent(),'2')
  await page.locator('#learner').selectOption('demo05')
  assert.equal(await page.locator('#total').textContent(),'1')
  await page.locator('input[value=dance]').check()
  assert.equal(await page.locator('#course-sign').isEnabled(),true)
  await page.locator('#course-sign').click()
  const admin=await page.context().newPage()
  admin.on('pageerror',e=>errors.push(e.message))
  await admin.goto('http://127.0.0.1:8766/admin.html')
  assert.equal(await admin.title(),'青禾云课 · 管理员端')
  assert.equal(await admin.locator('#course-sign').count(),0)
  assert.match(await admin.locator('.admin-notice').innerText(),/尚未实现身份认证/)
  assert.equal(await admin.locator('.future-card button:disabled').count(),2)
  assert.equal(await admin.locator('#records tr').count(),7)
  // A new sign-in must become visible in an already open admin page.
  await page.locator('input[value=vocal]').check()
  await page.locator('#course-sign').click()
  await admin.waitForFunction(()=>document.querySelectorAll('#records tr').length===8)

  assert.equal(await admin.locator('#records tr').count(),8)
  const dance=admin.locator('[data-course=dance]')
  assert.equal(await dance.locator('strong').nth(0).textContent(),'3')
  assert.equal(await dance.locator('strong').nth(1).textContent(),'3')
  assert.equal(await dance.locator('strong').nth(2).textContent(),'3')
  await admin.locator('#filter').selectOption('dance')
  assert.equal(await admin.locator('#records tr').count(),3)
  const downloadEvent=admin.waitForEvent('download');await admin.locator('#export').click()
  const download=await downloadEvent,stream=await download.createReadStream(),chunks=[]
  for await(const chunk of stream)chunks.push(chunk)
  const csv=Buffer.concat(chunks).toString('utf8')
  assert.match(csv,/舞蹈/);assert.ok(!csv.includes('书法'));assert.ok(csv.startsWith('\ufeff'))
  assert.ok(download.suggestedFilename().includes('虚构测试数据'))
  assert.ok(download.suggestedFilename().startsWith('青禾云课签到-'))
  await admin.locator('#filter').selectOption('all')
  await admin.screenshot({path:'/tmp/qhyun-admin.png',fullPage:true})
  await admin.locator('nav a[href="index.html"]').click()
  await admin.waitForURL('**/index.html')
  assert.equal(await admin.locator('#total').textContent(),'3')
  await admin.locator('nav a[href="admin.html"]').click()
  await admin.waitForURL('**/admin.html')
  for(const target of [page,admin])for(const width of [375,390,768,1440]){await target.setViewportSize({width,height:900});assert.ok(await target.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'overflow '+width)}
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:'/tmp/culture-student-mobile.png',fullPage:true})
  await page.locator('#learner').selectOption('demo01')
  await page.locator('input[value=vocal]').check()
  await page.evaluate(()=>{Storage.prototype.setItem=()=>{throw new DOMException('full','QuotaExceededError')}})
  await page.locator('#course-sign').click()
  assert.equal(await page.locator('#total').textContent(),'2')
  assert.match(await page.locator('#message').textContent(),/未保存/)
  await page.reload()
  assert.equal(await page.locator('#total').textContent(),'2')
  await page.evaluate(()=>localStorage.setItem('qhyun-class-demo-v1','broken'))
  await page.reload()
  assert.equal(await page.locator('#course-sign').isDisabled(),true)
  assert.match(await page.locator('#message').textContent(),/停用写入/)
  // Both prior formats must retain all records on actual page navigation.
  const model=require('../course-model')
  for(const kind of ['legacy','current','both']){
   const old=model.initial(),current=model.sign(old,'vocal')
   const saved=await browser.newContext()
   await saved.addInitScript(({kind,old,current})=>{
    if(localStorage.getItem('qhyun-class-demo-v1')!==null||localStorage.getItem('culture-palace-demo-v1')!==null)return
    if(kind!=='current')localStorage.setItem('culture-palace-demo-v1',JSON.stringify(old))
    if(kind!=='legacy')localStorage.setItem('qhyun-class-demo-v1',JSON.stringify(current))
   },{kind,old,current})
   const migrated=await saved.newPage()
   await migrated.goto('http://127.0.0.1:8766/'+entry)
   assert.equal(await migrated.locator('#total').textContent(),kind==='legacy'?'0':'1')
   await migrated.locator('nav a[href="admin.html"]').click()
   await migrated.waitForURL('**/admin.html')
   assert.equal(await migrated.locator('#records tr').count(),kind==='legacy'?4:5)
   if(kind!=='current')assert.equal(await migrated.evaluate(()=>JSON.parse(localStorage.getItem('culture-palace-demo-v1')).records.length),4)
   await saved.close()
  }
  assert.deepEqual(errors,[])
  console.log('PASS '+entry+': independent student/admin pages, cross-page live sync, navigation, reserved panels, course rules, CSV, persistence, mobile layout and storage failures')
 }finally{if(browser)await browser.close();server.kill()}
}
main().catch(e=>{console.error(e);process.exitCode=1})
