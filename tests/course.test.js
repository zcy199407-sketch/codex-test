const {test}=require('node:test')
const assert=require('node:assert/strict')
const m=require('../course-model')
const now=new Date(2026,9,25,10).getTime()
test('only fictional learners and known courses are accepted',()=>{
 const s=m.initial(now)
 assert.equal(m.validate(s),true)
 assert.throws(()=>m.sign(s,'' ,now),/课程/)
 assert.throws(()=>m.sign({...s,learnerId:'real-name'},'dance',now),/虚构/)
 assert.equal(m.validate({...s,records:[{learnerId:'real-name'}]}),false)
})
test('daily uniqueness is scoped to learner AND course',()=>{
 const s=m.initial(now),first=m.sign(s,'dance',now)
 assert.equal(s.records.length,4)
 assert.throws(()=>m.sign(first,'dance',now),/已完成/)
 const second=m.sign(first,'vocal',now)
 assert.equal(second.records.length,6)
 const other=m.sign({...second,learnerId:'demo05'},'dance',now)
 assert.equal(other.records.length,7)
 const tomorrow=new Date(now);tomorrow.setDate(tomorrow.getDate()+1)
 assert.equal(m.sign(second,'dance',tomorrow).records.length,7)
})
test('course stats distinguish today, total visits, and unique learners',()=>{
 const s=m.initial(now)
 const stats=m.stats(s.records,now)
 assert.deepEqual(stats.map(c=>[c.today,c.total,c.people]),[[1,2,2],[1,1,1],[1,1,1]])
 const next=m.sign({...s,learnerId:'demo05'},'calligraphy',now)
 const c=m.stats(next.records,now)[0]
 assert.equal(c.total,3);assert.equal(c.people,2);assert.equal(c.today,2)
})
test('CSV includes course names and fictional learners',()=>{
 const csv=m.csv(m.initial(now).records)
 assert.ok(csv.startsWith('\ufeff'))
 assert.match(csv,/测试学员/)
 for(const course of m.courses)assert.ok(csv.includes(course.name))
})
